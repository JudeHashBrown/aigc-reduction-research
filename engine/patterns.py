"""句式 / 段落 / 格式层的 AI 特征模式。

规则编号对照来源：
  S = 句式（thesis-optimizer L01-L07 / humanizer 模式 11-14 / 维基 AIPARALLEL,RO3,AINOCOPULA）
  P = 段落（humanizer 模式 1-2 / thesis-optimizer S01-S05）
  F = 格式（维基 AIDASH,AIBOLD,AILIST / thesis-optimizer F01-F03）

每条规则都必须能指出「命中了什么原文」——可核对是本引擎的信任基础。
"""
import re
from dataclasses import dataclass, field
from typing import Callable, List, Optional, Tuple


@dataclass
class Rule:
    rule_id: str
    name: str
    severity: str          # high / medium / low
    weight: float          # 临时权重，待探测标定
    explain: str
    fix: str = ""          # 怎么改。界面直接展示给用户，不能只给规则名
    regex: Optional[str] = None
    scope: str = "sentence"   # sentence / paragraph / document
    finder: Optional[Callable] = None   # 自定义查找器，返回 [(start, end, matched)]
    _compiled: object = field(default=None, repr=False)

    def compile(self):
        if self.regex and self._compiled is None:
            self._compiled = re.compile(self.regex)
        return self._compiled

    def find(self, text: str) -> List[Tuple[int, int, str]]:
        if self.finder:
            return self.finder(text)
        pat = self.compile()
        if not pat:
            return []
        return [(m.start(), m.end(), m.group(0)) for m in pat.finditer(text)]


# ---------- 自定义查找器 --------------------------------------------------

def find_ordinal_headings(text: str) -> List[Tuple[int, int, str]]:
    """通篇用「一、二、三」给小标题编号。

    lieflat 的触发标记是「小标题以序数词编号，且连续三个以上」。
    正文里的「首先…其次」不算——实测与人类写作无差别，是硬约束不是建议。
    所以这里只认独立成行的短行，且全文至少三处才报。
    """
    lines, hits = text.split("\n"), []
    pat = re.compile(r'^\s*(?:#{1,6}\s*)?(?:\*\*)?\s*'
                     r'(?:[一二三四五六七八九十]+[、.]|第[一二三四五六七八九十]+[、,，.]?)')
    pos = 0
    for line in lines:
        stripped = line.strip()
        m = pat.match(line)
        # 小标题：独立成行、不长、不以句号收尾
        if m and stripped and len(stripped) <= 30 and not stripped.endswith(("。", "！", "？")):
            hits.append((pos + m.start(), pos + m.end(), line[m.start():m.end()].strip()))
        pos += len(line) + 1
    return hits if len(hits) >= 3 else []


PARALLEL_CONJ = '且和以及与并'


def split_parallel_items(clause: str):
    """把一个顿号并列切成各项。

    末项常用连词收尾：「A、B和C」要先归一成「A、B、C」再切，
    否则只切出两项。消融函数必须共用这一份——各写各的必然漂移，
    实测消融在「高可靠性、强扩展性和好维护性」上直接失效。
    """
    norm = re.sub(rf'、([^、{PARALLEL_CONJ}]{{2,12}})[{PARALLEL_CONJ}]'
                  rf'([^、{PARALLEL_CONJ}]{{2,12}})$',
                  r'、\1、\2', clause)
    return [i for i in norm.split('、') if i]


def find_triple_parallel(text: str) -> List[Tuple[int, int, str]]:
    """三元及以上的并列，且各项长度接近（对称感强 = AI 味重）。

    命中：「高效、鲁棒且直观」「安全性、隐私性和可靠性」「更快、更稳、更智能」
    不命中：「北京、上海和粤港澳大湾区」（各项长度参差，更像真实枚举）

    注意：第一项常带动词前缀（「保证了数据的安全性」），长度不可比，
    因此只比较第 2 项及之后的长度。
    该规则对同长度的专名枚举（如「北京、上海、广州」）会有误报，
    命中原文会完整展示给用户核对，其真实预测力待探测标定后确认。
    """
    out = []
    CONJ = '且和以及与并'
    # 以标点切成分句，在分句内部找并列，避免跨句误配
    for cm in re.finditer(r'[^，。；：！？\n]+', text):
        clause, base = cm.group(0), cm.start()
        if '、' not in clause:
            continue
        items = split_parallel_items(clause)
        if len(items) < 3:
            continue
        tail = [len(i) for i in items[1:]]      # 跳过带前缀的首项
        if max(tail) - min(tail) > 2:
            continue
        if len(items[0]) < min(tail):           # 首项明显更短 → 不像并列
            continue
        out.append((base, base + len(clause), clause))
    return out


# 对冲词表。消融函数必须用同一份——两边各维护一份时，规则含「可能」
# 而消融不含，删掉「在一定程度上」后「似乎…可能」照样叠加，消融永远无效。
HEDGES_ZH = ['似乎', '可能', '或许', '大概', '在一定程度上', '某种程度上',
             '潜在', '一定的', '相对而言', '总体上']


def find_hedge_stack(text: str) -> List[Tuple[int, int, str]]:
    """对冲词叠加：一句里出现 2 个以上模糊限定 = 机器式不自信。"""
    hedges = HEDGES_ZH
    hits = []
    for h in hedges:
        for m in re.finditer(re.escape(h), text):
            hits.append((m.start(), m.end(), h))
    if len(hits) >= 2:
        hits.sort()
        return [(hits[0][0], hits[-1][1], '…'.join(h[2] for h in hits))]
    return []


